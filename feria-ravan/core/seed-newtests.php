/* ---------------------------------------------------------------------------
 | ساخت/به‌روزرسانی یک تست روانشناسی غربالگری
 |  $def: slug,title,short,desc,engine,audience,price,minutes,instr,sort
 |  $items: آرایهٔ [code, text, reverse?]  |  $scales: [code=>[title,color]]
 * -------------------------------------------------------------------------*/
function fr_seed_screening_test(array $def, array $items, array $scales, array $labels): int
{
    // ۱) ردیف تست روانشناسی
    $t = DB::one('SELECT id, audience FROM ' . DB::t('tests') . ' WHERE slug=?', [$def['slug']]);
    if (!$t) {
        $tid = DB::insert('tests', [
            'slug'         => $def['slug'],
            'title'        => $def['title'],
            'short_desc'   => $def['short'],
            'description'  => $def['desc'],
            'engine'       => $def['engine'],
            'audience'     => $def['audience'],
            'price_full'   => $def['price'],
            'question_count' => count($items),
            'est_minutes'  => $def['minutes'],
            'instructions' => $def['instr'],
            'status'       => 'active',
            'sort_order'   => $def['sort'],
        ]);
    } else {
        $tid = (int)$t['id'];
        // ستون‌های جدید/توضیحات همیشه به‌روز می‌شوند (بدون دست‌زدن به قیمت سفارشی مدیر)
        DB::run('UPDATE ' . DB::t('tests') . ' SET audience=?, title=?, short_desc=?, est_minutes=? WHERE id=?',
                [$def['audience'], $def['title'], $def['short'], $def['minutes'], $tid]);
    }

    // ۲) مقیاس‌ها (overall همیشه اول)
    $i = 0;
    foreach ($scales as $code => [$title, $color]) {
        $exists = DB::val('SELECT id FROM ' . DB::t('test_scales') . ' WHERE test_id=? AND code=?', [$tid, $code]);
        if (!$exists) DB::insert('test_scales', ['test_id'=>$tid,'code'=>$code,'title_fa'=>$title,'color'=>$color,'sort_order'=>$i]);
        $i++;
    }

    // ۳) سؤال‌ها + کلید (فقط اگر خالی است)
    if ((int)DB::val('SELECT COUNT(*) FROM ' . DB::t('questions') . ' WHERE test_id=?', [$tid]) === 0) {
        $labelsJson = json_encode($labels, JSON_UNESCAPED_UNICODE);
        foreach ($items as $n => $it) {
            [$code, $text] = $it; $rev = !empty($it[2]);
            $qid = fr_ins_q($tid, $n + 1, $text, 'likert', null, 1, 6, $labels[0], $labels[5]);
            DB::run('UPDATE ' . DB::t('questions') . ' SET labels=? WHERE id=?', [$labelsJson, $qid]);
            DB::insert('scoring_keys', [
                'test_id'=>$tid, 'question_id'=>$qid, 'scale_code'=>$code,
                'reverse'=>$rev ? 1 : 0, 'weight'=>1,
            ]);
        }
        DB::run('UPDATE ' . DB::t('tests') . ' SET question_count=? WHERE id=?', [count($items), $tid]);
    }
    return $tid;
}

