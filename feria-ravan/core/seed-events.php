/** نگاشت روز هفتهٔ فارسی به date('w') میلادی */
function fr_seed_wd(string $fa): int
{
    return ['یکشنبه'=>0,'دوشنبه'=>1,'سه‌شنبه'=>2,'چهارشنبه'=>3,'پنجشنبه'=>4,'جمعه'=>5,'شنبه'=>6][$fa] ?? 6;
}

/** تاریخ میلادی نخستین تکرار آیندهٔ روز هفتهٔ موردنظر (حداقل $minDays روز بعد) در ساعت مشخص */
function fr_seed_next_wd(int $wd, string $time, int $minDays = 5): string
{
    $now = new DateTime('now', new DateTimeZone('Asia/Tehran'));
    $cur = (int)$now->format('w');
    $diff = ($wd - $cur + 7) % 7;
    if ($diff === 0 || $diff < $minDays) $diff += 7 * (int)ceil(($minDays - $diff) / 7);
    $d = (clone $now)->modify('+' . $diff . ' day');
    return $d->format('Y-m-d') . ' ' . $time . ':00';
}

