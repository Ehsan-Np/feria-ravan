    [$c1, $c2] = $pals[$kind][$idx % count($pals[$kind])];
    $rot = ($idx * 37) % 360;   // چرخش فرم‌ها برای تنوع
    $svg = <<<SVG
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 675">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
