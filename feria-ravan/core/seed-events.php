    $dir = FR_ROOT . '/assets/uploads/' . $subdir;
    if (!is_dir($dir) && !@mkdir($dir, 0755, true)) return null;
    $fn = 'cover-' . $kind . '-' . ($idx + 1) . '.svg';
    // اگر فایل از قبل هست و محتوایش تغییر نکرده، دوباره‌نویسی لازم نیست
    if (is_file($dir . '/' . $fn) && md5_file($dir . '/' . $fn) === md5($svg))
        return 'assets/uploads/' . $subdir . '/' . $fn;
    if (@file_put_contents($dir . '/' . $fn, $svg) === false) return null;
    @chmod($dir . '/' . $fn, 0644);
    return 'assets/uploads/' . $subdir . '/' . $fn;
}

/**
 * upsert نرم رویداد: نبود → درج کامل؛ بود → فقط فیلدهای خالیِ نسخهٔ ۱٫۴ پر می‌شوند
 * (تنظیمات قیمت/همراه/تخفیف قبلی هرگز بازنویسی نمی‌شود)
 */
function fr_seed_event_upsert(array $e, array $defaults): void
{
    $row = DB::one('SELECT * FROM ' . DB::t('events') . ' WHERE kind=? AND title=?', [$e['kind'], $e['title']]);
    if (!$row) {
        DB::insert('events', $e + $defaults + ['status'=>'active','reg_open'=>1]);
        return;
    }
    $patch = [];
    foreach (['slug','short_desc','image','location','schedule_text'] as $col) {
        if (($row[$col] ?? null) === null || $row[$col] === '') $patch[$col] = $e[$col] ?? null;
    }
    if (($row['description'] ?? '') === '' || $row['description'] === null) $patch['description'] = $e['description'] ?? null;
    if ($patch) DB::update('events', $patch, 'id=?', [(int)$row['id']]);
}

