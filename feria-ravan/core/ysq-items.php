/* ---------------------------------------------------------------------------
 | سیدینگ یانگ
 |  ─ فرم بلند: همهٔ ۲۳۲ آیتم بالا
 |  ─ فرم کوتاه: ۵ آیتم اول هر طرحواره (۹۰ آیتم — زیرمجموعهٔ فرم بلند)
 * -------------------------------------------------------------------------*/
function fr_seed_ysq(): void
{
    $items = fr_ysq_long_items();

    $seedForm = function (string $slug, int $perSchema) use ($items): void {
        $t = DB::one("SELECT id FROM " . DB::t('tests') . " WHERE slug=?", [$slug]);
        if (!$t) return;
        $tid = (int)$t['id'];
        if ((int)DB::val("SELECT COUNT(*) FROM " . DB::t('questions') . " WHERE test_id=?", [$tid]) > 0) return;

        $num = 1;
        foreach ($items as $schema => $list) {
            foreach (array_slice($list, 0, $perSchema) as $text) {
                $qid = fr_ins_q($tid, $num++, $text, 'likert', null, 1, 6,
                                'اصلاً در مورد من صادق نیست', 'کاملاً در مورد من صادق است');
                DB::insert('scoring_keys', [
                    'test_id'=>$tid, 'question_id'=>$qid, 'scale_code'=>$schema,
                ]);
            }
        }
        DB::run("UPDATE " . DB::t('tests') . " SET question_count=? WHERE id=?", [$num - 1, $tid]);
    };

    $seedForm('ysq-long',  PHP_INT_MAX); // همهٔ آیتم‌ها = 232
    $seedForm('ysq-short', 5);           // 18 × 5 = 90
}
