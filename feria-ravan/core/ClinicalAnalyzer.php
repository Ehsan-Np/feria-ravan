                    '«اگر قرار بود این احساس رخوت و خستگی که مدتی است همراهتان است حرف بزند، به شما می‌گفت از چه چیزی در زندگی‌تان خسته شده است؟»',
                ];
                $defenseMechanisms = [
                    'primary'   => 'درون‌فکنی خشم و سرزنش خود (Introjection)',
