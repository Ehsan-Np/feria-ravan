        // ه) موتور هوش هیجانی بار-آن (Bar-On)
        elseif ($engine === 'baron' || str_contains($slug, 'baron')) {
            $stress = (float)($map['STRESS']['percent'] ?? 50);
            $intrap = (float)($map['INTRAP']['percent'] ?? 50);
            $interp = (float)($map['INTERP']['percent'] ?? 50);

            if ($stress <= 42) {
                $redFlags[] = [
                    'level' => 'warn',
                    'title' => 'شکنندگی در مدیریت استرس و مهار تکانه',
                    'desc'  => 'مراجع زیر فشار کاری یا خانوادگی سریعاً دچار فرسودگی عاطفی، واکنش‌های تکانشی یا تصمیمات هیجانی نسنجیده می‌شود.',
                ];
            }

            $hypotheses[] = [
                'category' => 'پویایی هوش هیجانی و انطباق',
                'title'    => 'ناهمترازی شایستگی‌های درون‌فردی و بین‌فردی',
