            $sessionOpeners = [
                '«در مواجهه با بحران‌ها، بیشتر احساساتتان را به درون می‌ریزید و خودخوری می‌کنید یا به بیرون واکنش نشان می‌دهید؟»',
            ];
            $defenseMechanisms = [
                'primary'   => 'سرکوب هیجانی و واکنش وارونه (Suppression)',
                'secondary' => 'انکار خستگی و فشار روانی',
            ];
