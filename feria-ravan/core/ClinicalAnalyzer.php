        // و) موتور MBTI
        elseif ($engine === 'mbti' || str_contains($slug, 'mbti')) {
            $hypotheses[] = [
                'category' => 'پویایی کارکردهای شناختی یونگ',
                'title'    => 'ساختار کارکرد مسلط و فعال‌شدن کارکرد کهتر زیر استرس (In the Grip of Inferior)',
