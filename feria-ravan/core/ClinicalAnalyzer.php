<?php
/**
 * ============================================================================
 *  موتور ارزیابی بالینی، روان‌پویشی و فرضیه‌سازی تشخیصی فریا روان (Clinical Analyzer)
 *  ─ فوق‌تخصص سنجش و اندازه‌گیری روانی و روان‌درمانی تحلیلی
 *  ─ فرضیه‌سازی ساختار شخصیت، سازمان ایگو و دینامیک روانی تعارضات ناهشیار
 *  ─ ارزیابی شاخص‌های ریسک (Red Flags)، مکانیسم‌های دفاعی فعال و سبک‌های دلبستگی
 *  ─ راهنمای اختصاصی اتاق درمان، مدیریت مقاومت‌ها، تله‌های انتقال و پروتکل‌های مداخله
 * ============================================================================
 */
declare(strict_types=1);

final class ClinicalAnalyzer
{
    /**
     * تولید خلاصه پرونده جامع بالینی برای مشاور و درمانگر
     */
    public static function generateCaseSummary(int $attemptId): ?array
    {
        return self::generateSummary($attemptId);
    }

    public static function generateSummary(int $attemptId): ?array
    {
        $at = DB::one('SELECT a.*, t.title AS test_title, t.slug AS test_slug, t.engine AS test_engine
                       FROM ' . DB::t('attempts') . ' a
                       JOIN ' . DB::t('tests') . ' t ON t.id=a.test_id
                       WHERE a.id=?', [$attemptId]);
        if (!$at) return null;

        $user = DB::one('SELECT id, first_name, last_name, mobile, email, created_at FROM ' . DB::t('users') . ' WHERE id=?', [$at['user_id']]);
        $results = DB::all('SELECT * FROM ' . DB::t('results') . ' WHERE attempt_id=?', [$attemptId]);
        $map = []; foreach ($results as $r) { $map[$r['scale_code']] = $r; }

        $validity = json_decode((string)($at['validity_json'] ?? ''), true) ?: [];

        $engine = (string)$at['test_engine'];
        $slug   = (string)$at['test_slug'];

        $redFlags      = [];
        $hypotheses    = [];
        $resistances   = [];
        $interventions = [];
        $sessionOpeners= [];
        $defenseMechanisms = [
            'primary'   => 'عقلانی‌سازی و کنترل شناختی (Intellectualization)',
            'secondary' => 'واپس‌رانی تنش‌های عاطفی و اجتناب رفتاری',
        ];

        // ۱. ارزیابی شاخص‌های ریسک و خطوط قرمز روان‌سنجی (Validity & Red Flags)
        if (!empty($validity['flags'])) {
            foreach ($validity['flags'] as $vf) {
                if ($vf['code'] === 'rush') {
                    $redFlags[] = [
                        'level' => 'warn',
                        'title' => 'پاسخ‌دهی شتاب‌زده (احتمال کم‌توجهی، تکانشگری یا دفاع اجتناب)',
                        'desc'  => 'مراجع آزمون را در زمانی کمتر از استاندارد انجام داده است؛ در جلسه اول لازم است صحت پاسخ‌ها با پرسش‌های کاوشگرانه سنجیده شود.',
                    ];
                } elseif ($vf['code'] === 'straight_line') {
                    $redFlags[] = [
                        'level' => 'danger',
                        'title' => 'الگوی خطی و عدم تمایز در پاسخ‌ها',
                        'desc'  => 'احتمال مقاومت در برابر سنجش، درماندگی عمیق یا بی‌انگیزگی شدید؛ نیازمند ارزیابی کیفی چهره‌به‌چهره.',
                    ];
                }
            }
        }

        // ۲. ارزیابی تخصصی بالینی و فرضیه‌سازی تشخیصی بر مبنای آزمون
        // الف) موتور DISC
        if ($engine === 'disc' || str_starts_with($slug, 'disc')) {
            $d = (float)($map['D']['percent'] ?? 50);
            $i = (float)($map['I']['percent'] ?? 50);
            $s = (float)($map['S']['percent'] ?? 50);
            $c = (float)($map['C']['percent'] ?? 50);

            if ($d >= 68 && $s <= 42) {
                $hypotheses[] = [
                    'category' => 'دینامیک روانی و ساختار ایگو',
                    'title'    => 'الگوی کنترل‌گری همه‌توان و اضطراب از انفعال (Dominance-Driven)',
                    'desc'     => 'مراجع انگیزهٔ بالایی برای تسلط بر محیط دارد اما در تحمل موقعیت‌های خارج از کنترل خود دچار تنش و تحریک‌پذیری شدید می‌شود. سازوکار بنیادین: احساس آسیب‌پذیری و نیازهای عاطفی را به نفع حفظ موضع قدرت واپس‌رانی می‌کند تا از تجربهٔ حس درماندگی اجتناب نماید.',
                ];
                $resistances[] = [
                    'style' => 'چالش بر سر صلاحیت درمانگر یا تلاش برای به دست گرفتن کنترل روند و زمان جلسه',
                    'guide' => 'از موضع بالادستی یا نصیحت‌گرانه سخن نگویید؛ درمان را به عنوان یک اتاق فکر و همکاری استراتژیک دوجانبه بازتعریف کنید و مراجع را مسئول نهایی انتخاب‌هایش بدانید.',
                ];
            }

            if ($s >= 68 && $d <= 40) {
                $hypotheses[] = [
                    'category' => 'تعارضات ناهشیار و سبک دلبستگی',
                    'title'    => 'واپس‌رانی خشم، اضطراب طرد و سازگاری بیمارگون (Suppressed Assertion)',
                    'desc'     => 'مراجع به دلیل ترس عمیق از تعارض یا قطع رابطه، خشم، مطالبات و تمایلات اصیل خود را پنهان می‌کند. این دینامیک معمولاً به خستگی مزمن، دردهای تنشی روان‌تنی (Somatization) یا رفتارهای نافرمانی انفعالی (Passive-Aggressive) در روابط صمیمی ختم می‌شود.',
                ];
                $resistances[] = [
                    'style' => 'موافقت کاذب، اطاعت ظاهری و لبخندهای دفاعی برای جلب رضایت درمانگر بدون تغییر واقعی',
                    'guide' => 'فضای امن بی قضاوت بسازید؛ به مراجع اجازه دهید با نظرات شما مخالفت کند؛ هرگونه ابراز جرأت‌ورزانه و مخالفت او را تقویت مثبت کنید.',
                ];
            }

            if ($c >= 68) {
                $hypotheses[] = [
                    'category' => 'منظومه دفاع‌های روانی',
                    'title'    => 'کمال‌گرایی ناسازگار و مکانیسم عقلانی‌سازی (Intellectualization)',
                    'desc'     => 'مراجع برای گریز از تجربهٔ هیجانات ناخوشایند، رویدادهای هیجانی را با منطق و قواعد خشک فرمول‌بندی می‌کند. باور بنیادین: «اگر بی‌نقص باشم، از انتقاد و فاجعه مصون خواهم ماند».',
                ];
                $resistances[] = [
                    'style' => 'بحث‌های فلسفی طولانی و درخواست مکرر شواهد علمی برای فرار از لمس رنج و احساسات درونی',
                    'guide' => 'گفت‌وگو را از تحلیل‌های انتزاعی به حس بدنی و احساسات لحظه‌ای هدایت کنید: «همین الان که این ماجرا را به یاد می‌آوری، در قفسه سینه یا تنفست چه تغییری رخ می‌دهد؟».',
                ];
            }

            if ($i >= 68 && $c <= 42) {
                $hypotheses[] = [
                    'category' => 'فرضیه تشخیصی افتراقی',
                    'title'    => 'شکنندگی عزت‌نفس و اعتیاد به تأیید اجتماعی (Approval-Seeking)',
                    'desc'     => 'ارزش وجودی مراجع به میزان بازخورد مثبت و توجه دیگران گره خورده است؛ در تنهایی مستعد افت ناگهانی خلق و احساس پوچی است.',
                ];
                $resistances[] = [
                    'style' => 'شیرین‌زبانی، تبدیل جلسه به شوخی و گفت‌وگوی صمیمانه برای خشنودسازی درمانگر',
                    'guide' => 'مرزهای حرفه‌ای جلسه را محکم نگه دارید و به آرامی و با همدلی، مراجع را به سمت موضوعات دردناک بازگردانید.',
                ];
            }

            $interventions = [
                'جلسه ۱: بازخورددهی نتایج آزمون به عنوان نقطه ورودی خنثی جهت پی‌ریزی اتحاد درمانی (Therapeutic Alliance).',
                'جلسه ۲: ترسیم چرخهٔ تعارض بین‌فردی مراجع در روابط نزدیک بر اساس تقابل سبک رفتاری با شریک زندگی/همکاران.',
                'جلسه ۳–۴: تمرین رفتارهای جایگزین و تکنیک‌های تنظیم هیجان متناسب با سبک شناختی.',
                'جلسه ۵ به بعد: بازسازی شناخت‌های خودکار ناکارآمد و یکپارچه‌سازی لایه‌های رفتاری واپس‌رانده‌شده.',
            ];
            $sessionOpeners = [
                '«در کارنامه آزمون شما، انگیزه و تلاش فوق‌العاده‌ای برای پیشبرد اهداف دیده می‌شود؛ در خلوت خودتان، این مسئولیت‌پذیری مداوم چقدر شما را خسته می‌کند؟»',
                '«آیا تا به حال پیش آمده که برای حفظ آرامش رابطه، حرفی که ته دلتان بوده را ماه‌ها در خودتان سرکوب کنید؟»',
            ];
            $defenseMechanisms = [
                'primary'   => ($c >= 60 ? 'عقلانی‌سازی و کنترل‌گری (Intellectualization)' : 'واپس‌رانی و سازگاری انفعالی (Repression)'),
                'secondary' => ($d >= 60 ? 'واکنش وارونه و جبران افراطی' : 'اجتناب رفتاری و صلح‌طلبی کاذب'),
            ];
        }

        // ب) موتور NEO (پنج عامل بزرگ شخصیت)
        elseif ($engine === 'neo' || str_starts_with($slug, 'neo') || $engine === 'likert') {
            $n = (float)($map['N']['percent'] ?? 50);
            $e = (float)($map['E']['percent'] ?? 50);
            $o = (float)($map['O']['percent'] ?? 50);
            $a = (float)($map['A']['percent'] ?? 50);
            $c = (float)($map['C']['percent'] ?? 50);

            if ($n >= 65) {
                $hypotheses[] = [
                    'category' => 'سازمان روانی و ثبات هیجانی',
                    'title'    => 'نشانگان آسیب‌پذیری عاطفی و بیش‌فعالی سیستم تهدید (High Neuroticism)',
                    'desc'     => 'آستانه پایین برانگیختگی در برابر استرسورهای محیطی؛ گرایش مزمن به تجربه اضطراب، نشخوار فکری و سوگیری شناختی نسبت به تهدید. احتمال بالای علائم اضطرابی یا نوسانات خلقی نیازمند غربالگری بالینی است.',
                ];
                $resistances[] = [
                    'style' => 'فاجعه‌سازی از روند درمان و تردید مکرر درباره بهبود‌پذیری مشکلات',
                    'guide' => 'بر تکنیک‌های تنظیم هیجان، تثبیت فیزیولوژیک (تنفس و ذهن‌آگاهی) و تجربه‌های موفق کوچک تمرکز کنید.',
                ];
            }

            if ($n >= 65 && $e <= 40) {
                $hypotheses[] = [
                    'category' => 'فرضیه تشخیصی افتراقی PDM-2 / DSM-5',
                    'title'    => 'الگوی شخصیتی دیستیمیک/افسرده‌خو (Dysthymic / Depressive Constellation)',
                    'desc'     => 'ترکیب روان‌رنجورخویی بالا و برون‌گرایی پایین نشان‌دهندهٔ احساس مزمن ملال، انزوای عاطفی، لذت‌نبُردگی و کمبود دوپامین در سیستم پاداش اجتماعی است.',
                ];
            }

            if ($n >= 60 && $c <= 40) {
                $hypotheses[] = [
                    'category' => 'کنترل تکانه و عملکرد ایگو',
                    'title'    => 'تکانشگری زیر استرس و ناتوانی در تعویق ارضای تکانه‌ها (Under-Controlled Profile)',
                    'desc'     => 'مراجع هنگام اوج‌گیری هیجانات منفی مستعد رفتارهای تکانشی آسیب‌رسان (پرخوری عصبی، خریدهای وسواسی، پرخاشگری کلامی یا ترک ناگهانی موقعیت) است.',
                ];
            }

            if ($c >= 70 && $n >= 60) {
                $hypotheses[] = [
                    'category' => 'دینامیک روانی تعارضات',
                    'title'    => 'کمال‌گرایی اضطرابی و فرسودگی سوپرایگو (Compulsive / Hyper-Responsible Ego)',
                    'desc'     => 'سوپرایگوی سخت‌گیر و تنبیه‌گر که مراجع را ملزم به عملکرد ۱۰۰٪ بی‌نقص می‌کند. هر خطای کوچک منجر به احساس گناه شدید و خودسرزنش‌گری ویرانگر می‌شود.',
                ];
            }

            if ($a >= 68 && $n >= 55) {
                $hypotheses[] = [
                    'category' => 'سبک دلبستگی و روابط بین‌فردی',
                    'title'    => 'دلبستگی اضطرابی-هم‌وابسته و فداکاری مفرط (Self-Sacrificing Schema)',
                    'desc'     => 'مراجع نیازهای خود را قربانی خشنودی دیگران می‌کند تا از تجربه وحشتناک طرد شدن یا تنها ماندن پیشگیری نماید.',
                ];
            }

            $interventions = [
                'جلسه ۱: ایجاد اتحاد درمانی امن و همدلانه جهت کاهش مقاومت‌های ناشی از اضطراب ارزیابی.',
                'جلسه ۲: ترسیم پروفایل پنج‌عاملی شخصیت به عنوان نقشه سیم‌کشی ژنتیکی و زیستی مراجع.',
                'جلسه ۳–۴: آموزش مهارت‌های شناختی-رفتاری (CBT) جهت مهار نشخوار ذهنی و تعدیل کمال‌گرایی.',
                'جلسه ۵ به بعد: کار بر روی یکپارچگی ابعاد درون‌گرایی/برون‌گرایی و تنظیم اهداف انطباقی با رویکرد پذیرش و تعهد (ACT).',
            ];
            $sessionOpeners = [
                '«در نیمرخ شخصیتی شما، حساسیت عاطفی عمیقی دیده می‌شود؛ این حساسیت در کجاها به عنوان یک قطب‌نمای قوی به کمکتان آمده و کجاها شما را تحت فشار قرار داده است؟»',
                '«وقتی اوضاع بر خلاف میلتان پیش می‌رود، اولین گفت‌وگوی درونی که در ذهنتان با خودتان شروع می‌کنید چیست؟»',
            ];
            $defenseMechanisms = [
                'primary'   => ($n >= 60 ? 'نشخوار فکری و درون‌فکنی احساس گناه (Introjection)' : 'والایش و سازگاری انطباقی'),
                'secondary' => ($c >= 60 ? 'عقلانی‌سازی و جداسازی عاطفی (Isolation of Affect)' : 'انکار و فرار به سرگرمی'),
            ];
        }

        // ج) موتور غربالگری بالینی اضطراب و افسردگی (Screen)
        elseif ($engine === 'screen' || str_contains($slug, 'anxiety') || str_contains($slug, 'depression')) {
            $isAnx = str_contains($slug, 'anxiety');
            $overall = (float)($map['overall']['percent'] ?? 50);

            if ($isAnx) {
                if ($overall >= 55) {
                    $redFlags[] = [
                        'level' => ($overall >= 75 ? 'danger' : 'warn'),
                        'title' => 'برافراشتگی بالینی شاخص‌های اضطراب حاد',
                        'desc'  => 'گزارش سطوح متوسط تا شدید اضطراب بدنی و شناختی؛ نیازمند ارزیابی حملات پانیک، اضطراب فراگیر (GAD) و بررسی ضرورت مداخله دارویی مکمل.',
                    ];
                }
                $hypotheses[] = [
                    'category' => 'فرضیه‌سازی تشخیصی و دینامیک اضطراب',
                    'title'    => 'عدم تحمل بلاتکلیفی و بیش‌فعالی چرخه فاجعه‌سازی شناختی',
                    'desc'     => 'مراجع رویدادهای خنثی را به عنوان تهدید بالقوه تفسیر کرده و با رفتارهای ایمنی‌بخش (چک کردن، اطمینان‌طلبی و اجتناب) چرخه اضطراب را تقویت می‌کند.',
                ];
                $resistances[] = [
                    'style' => 'نیاز به راهکارهای معجزه‌آسا و فوری، یا ابراز ناتوانی از مواجهه با محرک‌های اضطراب‌زا',
                    'guide' => 'اضطراب را به عنوان یک سیگنال محافظ فیزیولوژیک معتبرسازی کنید؛ تأکید کنید که هدف درمان، حذف کامل اضطراب نیست بلکه افزایش تحمل پریشانی است.',
                ];
                $interventions = [
                    'آموزش روانی فیزیولوژی اضطراب و تفاوت خطر واقعی با احساس تهدید.',
                    'تمرینات تنفس آهسته دیافراگمی و بازآرایی توجه (Attention Training Technique).',
                    'مواجهه تدریجی درون‌زاد (Interoceptive Exposure) با حس‌های بدنی اضطراب.',
                    'چالش با خطاهای شناختی فاجعه‌سازی و ذهن‌خوانی.',
                ];
                $sessionOpeners = [
                    '«وقتی اضطراب به سراغتان می‌آید، بدنتان زودتر زنگ خطر را می‌زند یا ذهنتان شروع به ساختن سناریوهای منفی می‌کند؟»',
                ];
                $defenseMechanisms = [
                    'primary'   => 'جسمانی‌سازی و اجتناب رفتاری (Somatization & Avoidance)',
                    'secondary' => 'ابطال جادویی و کنترل‌گری وسواسی (Undoing)',
                ];
            } else {
                // افسردگی
                if ($overall >= 55) {
                    $redFlags[] = [
                        'level' => ($overall >= 75 ? 'danger' : 'warn'),
                        'title' => 'نشانگان بالینی خلق افسرده و کاهش انرژی حیاتی',
                        'desc'  => 'کندی روانی-حرکتی، لذت‌نبُردگی و افکار ناامیدی؛ غربالگری فوری افکار خودکشی و بررسی ایمنی الزامی است.',
                    ];
                }
                $hypotheses[] = [
                    'category' => 'دینامیک روانی افسردگی و درماندگی',
                    'title'    => 'مثلث شناختی بک و درماندگی آموخته‌شده (Learned Helplessness)',
                    'desc'     => 'نگرش منفی عمیق نسبت به خود («من بی‌کفایتم»)، جهان («هیچ‌کس مرا درک نمی‌کند») و آینده («اوضاع هرگز درست نخواهد شد»). در بافت پویشی: خشم معطوف به درون ناشی از فقدان یا ناکامی حل‌نشده.',
                ];
                $resistances[] = [
                    'style' => 'انفعال، عدم انجام تکالیف خانگی با این توجیه که «هیچ فایده‌ای ندارد»',
                    'guide' => 'تکالیف را فوق‌العاده خرد و عملیاتی کنید (میکرو-رفتارها)؛ از تله بحث منطقی پرهیز کرده و فعال‌سازی رفتاری گام‌به‌گام را به کار گیرید.',
                ];
                $interventions = [
                    'پروتکل فعال‌سازی رفتاری (Behavioral Activation): ثبت فعالیت و اتصال مجدد به منابع تقویت مثبت.',
                    'بررسی ایمنی، تدوین طرح ایمنی فردی (Safety Plan) در صورت وجود افکار تاریک.',
                    'تنظیم بهداشت خواب و ریتم شبانه‌روزی (Circadian Rhythm Therapy).',
