                'desc'     => 'طرحواره‌های فعال مراجع (' . implode('، ', array_slice($activeSchemas, 0, 5)) . ') ریشه در تجارب ناکام‌کننده نیازهای عاطفی دوران رشد دارند. این باورها لنزهای ادراکی منجمدی هستند که الگوهای رابطه، شکست یا درماندگی را در بزرگسالی بازتولید می‌کنند.',
