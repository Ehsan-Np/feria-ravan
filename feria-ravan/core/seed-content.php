require_once dirname(__DIR__) . '/includes/functions.php';

function fr_seed_content(): void
{
    if (DB::setting('content_seeded') === '1') return;

    fr_seed_disc('disc-family',   fr_disc_family_items());
    fr_seed_disc('disc-business', fr_disc_business_items());
    fr_seed_neo();
    fr_seed_templates();

    require_once __DIR__ . '/ysq-items.php';
    if (function_exists('fr_seed_ysq')) fr_seed_ysq();
    require_once __DIR__ . '/ysq-templates.php';
    if (function_exists('fr_seed_ysq_templates')) fr_seed_ysq_templates();

    // تست‌های روانشناسی نسخهٔ ۱٫۲ (اضطراب/افسردگی/رضایت شغلی + نسخه‌های مدیران)
    require_once __DIR__ . '/seed-newtests.php';
    if (function_exists('fr_seed_newtests')) fr_seed_newtests();

    // تست‌های روانشناسی نسخهٔ ۱٫۸ (گاردنر ۹ هوش ۹۰سؤال + هوش هیجانی شوت ۳۳سؤال)
    require_once __DIR__ . '/seed-mseq.php';
    if (function_exists('fr_seed_mseq_tests')) fr_seed_mseq_tests();

    /* نسخهٔ ۱٫۳ دیگر سید نمی‌شود — از نسخهٔ ۱٫۵ فقط مجموعهٔ ۱۰ کارگاه + ۱۰ دورهٔ
       سورس گیت‌هاب ثبت می‌شود تا فهرست رویدادها دقیقاً همان باشد که مالک خواسته */
    require_once __DIR__ . '/seed-events.php';

    // نسخهٔ ۱٫۵: آرشیو کامل ۱۰ کارگاه + ۱۰ دوره — دقیقاً مطابق سورس گیت‌هاب فریا
    // (اقلام قدیمیِ v4 بدون ثبت‌نام به‌صورت خودکار بایگانی می‌شوند)
    if (function_exists('fr_seed_events_v5')) fr_seed_events_v5();

    // نسخهٔ ۱٫۴: سیستم بوکینگ مشاوره (مشاوران، خدمات، قوانین هفتگی، اسلات‌ها)
    if (function_exists('fr_seed_consult')) fr_seed_consult();

    fr_seed_test_texts_v6();              // توضیحات پیش‌فرض کامل تست‌های روانشناسی + تیزر نسخهٔ رایگان (۱٫۶)
    DB::setSetting('content_seeded', '1');
}

/* ---------------------------------------------------------------------------
 | درج یک سؤال + کلیدش
 * -------------------------------------------------------------------------*/
function fr_ins_q(int $testId, int $num, string $text, string $format,
                  ?array $options, int $sMin, int $sMax, ?string $minL, ?string $maxL): int
{
    return DB::insert('questions', [
        'test_id'=>$testId,'number'=>$num,'text'=>$text,'format'=>$format,
        'options'=>$options ? json_encode($options, JSON_UNESCAPED_UNICODE) : null,
        'scale_min'=>$sMin,'scale_max'=>$sMax,'min_label'=>$minL,'max_label'=>$maxL,
    ]);
}

/* ---------------------------------------------------------------------------
 | DISC — هر آیتم: ۴ وصف + ترتیب حروف D/I/S/C
 *   format = mostleast  |  کلید: meta.letters
 * -------------------------------------------------------------------------*/
function fr_seed_disc(string $slug, array $items): void
{
    $t = DB::one("SELECT id FROM " . DB::t('tests') . " WHERE slug=?", [$slug]);
    if (!$t || (int)DB::val("SELECT COUNT(*) FROM " . DB::t('questions') . " WHERE test_id=?", [$t['id']]) > 0) return;
    $tid = (int)$t['id'];
    foreach ($items as $i => [$opts, $letters]) {
        $qid = fr_ins_q($tid, $i + 1, 'کدام توصیف بیشترین و کدام کمترین شباهت را به شما دارد؟',
                        'mostleast', $opts, 0, 3, null, null);
        DB::insert('scoring_keys', [
            'test_id'=>$tid,'question_id'=>$qid,'scale_code'=>'D',
            'meta'=>json_encode(['letters'=>$letters], JSON_UNESCAPED_UNICODE),
        ]);
    }
    DB::run("UPDATE " . DB::t('tests') . " SET question_count=? WHERE id=?", [count($items), $tid]);
}

