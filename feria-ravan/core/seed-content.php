function fr_seed_neo(): void
{
    $t = DB::one("SELECT id FROM " . DB::t('tests') . " WHERE slug='neo'");
    if (!$t || (int)DB::val("SELECT COUNT(*) FROM " . DB::t('questions') . " WHERE test_id=?", [$t['id']]) > 0) return;
    $tid = (int)$t['id'];
    foreach (fr_neo_items() as $i => [$text, $scale, $rev]) {
        $qid = fr_ins_q($tid, $i + 1, $text, 'likert', null, 1, 5,
                        'کاملاً مخالفم', 'کاملاً موافقم');
        DB::insert('scoring_keys', [
            'test_id'=>$tid,'question_id'=>$qid,'scale_code'=>$scale,'reverse'=>$rev,
        ]);
    }
}

/* ---------------------------------------------------------------------------
 | قالب‌های تحلیل فارسی (نگارش بومی و حرفه‌ای)
 *   band:  'any' = هر باند (خلاصه)  |  high/very_high = نسخه ویژه برای نمرات برجسته
 *   level: free / full
 * -------------------------------------------------------------------------*/
function fr_ins_tpl(int $testId, ?string $scale, string $band, string $level, string $title, string $body): void
{
    // ۱٫۸: گارد تکرار — بدون این رفع، هر اجرای reseed?force=1 قالب‌های DISC/NEO را دوباره درج می‌کرد
    $exists = DB::val('SELECT id FROM ' . DB::t('analysis_templates') .
                      ' WHERE test_id=? AND (scale_code<=>?) AND band=? AND level=?',
                      [$testId, $scale, $band, $level]);
    if ($exists) return;
    DB::insert('analysis_templates', [
        'test_id'=>$testId,'scale_code'=>$scale,'band'=>$band,'level'=>$level,'title'=>$title,'body'=>$body,
    ]);
}

