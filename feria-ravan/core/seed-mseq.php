                               array $overallRows, string $overallTitle): int
{
    /* ۱) ردیف تست روانشناسی — درج یا به‌روزرسانی متن‌ها (بدون دست‌زدن به قیمت مدیر) */
    $t = DB::one('SELECT id FROM ' . DB::t('tests') . ' WHERE slug=?', [$def['slug']]);
    if (!$t) {
        $tid = (int)DB::insert('tests', [
            'slug'           => $def['slug'],
            'title'          => $def['title'],
            'short_desc'     => $def['short'],
            'description'    => $def['desc'],
            'free_teaser'    => $def['teaser'],
            'engine'         => 'mslikert',
            'audience'       => $def['audience'],
            'price_full'     => $def['price'],
            'free_enabled'   => 1,
            'question_count' => count($items),
            'est_minutes'    => $def['minutes'],
            'instructions'   => $def['instr'],
            'status'         => 'active',
            'sort_order'     => $def['sort'],
        ]);
    } else {
        $tid = (int)$t['id'];
        DB::run('UPDATE ' . DB::t('tests') .
                ' SET title=?, short_desc=?, description=?, instructions=?, est_minutes=? WHERE id=?',
                [$def['title'], $def['short'], $def['desc'], $def['instr'], $def['minutes'], $tid]);
    }

    /* ۲) مقیاس‌ها */
    $i = 0;
    foreach ($scales as $code => [$title, $color]) {
        $exists = DB::val('SELECT id FROM ' . DB::t('test_scales') . ' WHERE test_id=? AND code=?', [$tid, $code]);
        if (!$exists) {
            DB::insert('test_scales', [
                'test_id' => $tid, 'code' => $code, 'title_fa' => $title,
                'color' => $color, 'sort_order' => $i,
            ]);
        }
        $i++;
    }

    /* ۳) سؤال‌ها + کلید نمره‌گذاری (فقط اگر پرسشی وجود ندارد) */
    if ((int)DB::val('SELECT COUNT(*) FROM ' . DB::t('questions') . ' WHERE test_id=?', [$tid]) === 0) {
        $labelsJson = json_encode($labels, JSON_UNESCAPED_UNICODE);
        $n = 0;
        foreach ($items as $it) {
            $n++;
            $code = $it[0]; $text = $it[1]; $rev = !empty($it[2] ?? null);
            $qid = fr_ins_q($tid, $n, $text, 'likert', null, 1, 5, $labels[0], $labels[4]);
            DB::run('UPDATE ' . DB::t('questions') . ' SET labels=? WHERE id=?', [$labelsJson, $qid]);
            DB::insert('scoring_keys', [
                'test_id' => $tid, 'question_id' => $qid, 'scale_code' => $code,
                'reverse' => $rev ? 1 : 0, 'weight' => 1,
            ]);
        }
        DB::run('UPDATE ' . DB::t('tests') . ' SET question_count=? WHERE id=?', [$n, $tid]);
    }

    /* ۴) قالب‌های تحلیل —free: تیزر هر مقیاس (band=any) */
    foreach ($freeTxt as $code => $txt) {
        fr_mseq_tpl($tid, $code, 'any', 'free',
            'نگاه کوتاه به «' . ($scales[$code][0] ?? $code) . '»', $txt);
    }
    if (isset($overallRows['free'])) {
        fr_mseq_tpl($tid, 'overall', 'any', 'free', 'نگاه کلی', (string)$overallRows['free']);
    }

    /* ۵) قالب‌های تحلیل — full: سه باند اصلی برای هر مقیاس */
    foreach ($fullTpl as $code => $bands) {
        foreach ($bands as $band => $body) {
            $bandFa = ['high' => 'برجسته', 'medium' => 'متعادل', 'low' => 'فرصت رشد'][$band] ?? $band;
            fr_mseq_tpl($tid, $code, $band, 'full',
                'واکاوی عمیق «' . ($scales[$code][0] ?? $code) . '» — سطح ' . $bandFa, $body);
        }
    }

    /* ۶) ردیف‌های کلی (overall) */
    if ($overallFull !== '') {
        // جمع‌بندی کلینیکی در انتهای گزارش ویژه (scale_code NULL + band overall)
        fr_mseq_tpl($tid, null, 'overall', 'full', $overallTitle, $overallFull);
        // ردیف overall در جدول نتایج — متن مشترک برای همهٔ باندها
        foreach (['very_low', 'low', 'medium', 'high', 'very_high'] as $b) {
            fr_mseq_tpl($tid, 'overall', $b, 'full', 'خوانش نمرهٔ کلی', $overallFull);
        }
    } else {
        // متن اختصاصی هر باند کلی (مثل هوش هیجانی با هنجار ۱۲۴)
        foreach (['very_low', 'low', 'medium', 'high', 'very_high'] as $b) {
            if (isset($overallRows[$b])) {
                fr_mseq_tpl($tid, 'overall', $b, 'full', 'خوانش نمرهٔ کلی', (string)$overallRows[$b]);
            }
        }
    }

    return $tid;
}
