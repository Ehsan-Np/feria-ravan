            fr_tpl($tid, 'overall', $band, 'free', 'سطح اضطراب شما: ' . $sevTitle[$band] . $suffix, '<p>' . $txt . '</p>');
            fr_tpl($tid, 'overall', $band, 'full', 'تحلیل کامل اضطراب — سطح ' . $sevTitle[$band] . $suffix,
                   '<p>' . $txt . '</p><br>' . $fullBase);
        }
        foreach (fr_texts_anxiety_facets() as $code => [$title, $free, $full]) {
            fr_tpl($tid, $code, 'any', 'free', $title, '<p>' . $free . '</p>');
            fr_tpl($tid, $code, 'any', 'full', $title, '<p>' . $full . '</p>');
        }
        // جمع‌بندی در نسخهٔ ویژه
        fr_tpl($tid, null, 'overall', 'full', 'جمع‌بندی و مسیر پیشِ‌رو',
