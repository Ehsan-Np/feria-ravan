               '<p>بهبود افسردگی، مسیرِ «کم‌کردن تدریجیِ بدهیِ انرژی» است، نه یک تصمیم یک‌روزه. کوچک‌ترین فعالیتِ زمان‌بندی‌شده را از همین امروز در تقویم‌تان ثبت کنید. و به یاد داشته باشید: خواستنِ کمک، نشانهٔ قوت است. در صورت شدید بودن علائم، درمان تخصصی انتخابِ اول است.</p>');
