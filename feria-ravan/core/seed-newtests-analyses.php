/* ===========================================================================
 |  درج یک قالب تحلیل (گارد تکرار)
 * ==========================================================================*/
function fr_tpl(int $tid, ?string $scale, string $band, string $level, string $title, string $body): void
{
    $exists = DB::val('SELECT id FROM ' . DB::t('analysis_templates') .
                      ' WHERE test_id=? AND (scale_code<=>?) AND band=? AND level=?', [$tid, $scale, $band, $level]);
    if ($exists) return;
    DB::insert('analysis_templates', [
        'test_id'=>$tid, 'scale_code'=>$scale, 'band'=>$band, 'level'=>$level,
        'title'=>$title, 'body'=>$body,
    ]);
}

