               '<p>بهترین حیطه برای شروعِ تغییر، ضعیف‌ترین حیطه‌ای است که «بیشترین نفوذِ عملی» را دارید. هفتهٔ آینده فقط یک اقدام از برنامهٔ ۴ فازی آن حیطه را اجرا کنید — شتابِ تغییرِ رضایت شغلی، پیوسته و کوچک است نه انفجاری.</p>');
