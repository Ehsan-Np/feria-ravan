 * ==========================================================================*/
function fr_seed_screening_templates(int $tAnx, int $tDep, int $tJs,
                                     int $tAnxM, int $tDepM, int $tJsM): void
{
    $sevTitle = ['very_low'=>'حداقل','low'=>'خفیف','medium'=>'متوسط','high'=>'متوسط رو به شدید','very_high'=>'شدید'];
    $jsTitle  = ['very_low'=>'پایین','medium'=>'متوسط','high'=>'بالا'];

    /* ---------- اضطراب (عمومی + مدیران) ---------- */
    foreach ([[$tAnx, false], [$tAnxM, true]] as [$tid, $mgr]) {
