function fr_seed_comprehensive_tests(bool $force = false): void
{
    if (!$force && DB::setting('content_seeded_v33') === '1') return;

    fr_update_test_categories();
    fr_seed_mbti_test();
    fr_seed_holland_test();
    fr_seed_ysq_standard_test();
    fr_seed_baron_eq_test();
    fr_seed_mmpi_test();
    fr_seed_raven_test();
    fr_seed_wais_test();

    DB::setSetting('content_seeded_v33', '1');
}

/** به‌روزرسانی ستون category برای تست‌های پیشین */
function fr_update_test_categories(): void
{
    $p = defined('DB_PREFIX') ? DB_PREFIX : 'fr_';
    try {
        DB::run("ALTER TABLE `{$p}tests` ADD COLUMN IF NOT EXISTS `category` ENUM('clinical','personality','intelligence') NOT NULL DEFAULT 'personality' AFTER `audience`");
        DB::run("ALTER TABLE `{$p}tests` ADD KEY IF NOT EXISTS `ix_cat` (`category`)");
    } catch (Throwable $e) {}

    DB::run("UPDATE `{$p}tests` SET `category`='clinical' WHERE `slug` IN ('depression','depression-manager','anxiety','anxiety-manager','ysq','ysq-short','ysq-long','mmpi')");
    DB::run("UPDATE `{$p}tests` SET `category`='personality' WHERE `slug` IN ('disc-family','disc-business','neo','neo-manager','mbti')");
    DB::run("UPDATE `{$p}tests` SET `category`='intelligence' WHERE `slug` IN ('gardner-mi','eq-shutte','jobsat','jobsat-manager','holland','baron-eq','raven','wais')");
}

function fr_upsert_test_def(array $def): int
{
    $row = DB::one("SELECT id FROM " . DB::t('tests') . " WHERE slug=?", [$def['slug']]);
    if ($row) {
        $id = (int)$row['id'];
        DB::update('tests', [
            'title'          => $def['title'],
            'short_desc'     => $def['short_desc'],
            'description'    => $def['description'],
            'category'       => $def['category'] ?? 'personality',
            'engine'         => $def['engine'] ?? 'likert',
            'audience'       => $def['audience'] ?? 'general',
            'question_count' => $def['question_count'] ?? 0,
            'est_minutes'    => $def['est_minutes'] ?? 15,
            'price_full'     => $def['price_full'] ?? 0,
            'price_sale'     => $def['price_sale'] ?? null,
            'free_enabled'   => $def['free_enabled'] ?? 1,
            'sort_order'     => $def['sort_order'] ?? 10,
            'status'         => 'active',
        ], 'id=?', [$id]);
        return $id;
    }
    return (int)DB::insert('tests', $def + ['status'=>'active','created_at'=>date('Y-m-d H:i:s')]);
}

if (!function_exists('fr_ins_q_comp')) {
    function fr_ins_q_comp(int $testId, int $num, string $text, string $format,
                           ?array $options, int $sMin, int $sMax, ?string $minL, ?string $maxL): int
    {
        return DB::insert('questions', [
            'test_id'   => $testId,
            'number'    => $num,
            'text'      => $text,
            'format'    => $format,
            'options'   => $options ? json_encode($options, JSON_UNESCAPED_UNICODE) : null,
            'scale_min' => $sMin,
            'scale_max' => $sMax,
            'min_label' => $minL,
            'max_label' => $maxL,
            'active'    => 1,
        ]);
    }
}

if (!function_exists('fr_ins_tpl_comp')) {
    function fr_ins_tpl_comp(int $testId, ?string $scaleCode, string $band, string $level,
                             string $title, string $body, ?string $growth = null, int $sort = 0): void
    {
        $old = DB::one("SELECT id FROM " . DB::t('analysis_templates') .
                       " WHERE test_id=? AND scale_code=? AND band=? AND level=?",
                       [$testId, $scaleCode, $band, $level]);
        if ($old) {
            DB::update('analysis_templates', [
                'title'       => $title,
                'body'        => $body,
                'growth_plan' => $growth,
                'sort_order'  => $sort,
            ], 'id=?', [$old['id']]);
        } else {
            DB::insert('analysis_templates', [
                'test_id'     => $testId,
                'scale_code'  => $scaleCode,
                'band'        => $band,
                'level'       => $level,
                'title'       => $title,
                'body'        => $body,
                'growth_plan' => $growth,
                'sort_order'  => $sort,
            ]);
        }
    }
}

